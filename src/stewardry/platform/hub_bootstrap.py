"""Adding Stewardry's client and persona users to the hub realm (ADR 0008).

`bootstrap()` reads `deploy/hub/stewardry-realm-additions.json` and, through
the Keycloak admin REST API:

1. checks that the configured issuer is a local hub and that the hub's own
   discovery document names exactly that issuer;
2. snapshots every client and client scope the broker's realm defines;
3. creates the `stewardry` client if it is missing, and each persona user if
   missing (through partial import, to keep the fixed IDs when Keycloak
   allows it). Anything that already exists is left alone, even if it
   differs from the file; differences are reported, never "fixed";
4. checks that the broker's clients and scopes are byte-identical afterwards;
5. writes generated secrets to a git-ignored 0600 file and a proposed access
   mapping with the actual subjects.

The admin credential comes from the environment and is never printed,
logged, or stored. Generated secrets are written only to the secrets file;
only their entry names are reported.
"""

import json
import os
import secrets
import stat
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit

import httpx2
import yaml

LOCAL_HOSTS = frozenset({"localhost", "127.0.0.1"})
CLIENT_ENTRY = "STEWARDRY_HUB_CLIENT_SECRET"  # an entry name, not a value
# Client settings compared on an existing client (reported if different, never changed).
CHECKED_CLIENT_FIELDS = (
    "publicClient",
    "standardFlowEnabled",
    "directAccessGrantsEnabled",
    "implicitFlowEnabled",
    "serviceAccountsEnabled",
    "redirectUris",
    "defaultClientScopes",
    "optionalClientScopes",
)


class BootstrapError(Exception):
    """The bootstrap stopped. Nothing after the failing step was done."""


@dataclass
class BootstrapResult:
    client: str = ""  # "created" | "existed"
    created_users: list[str] = field(default_factory=list)
    existing_users: list[str] = field(default_factory=list)
    subjects: dict[str, str] = field(default_factory=dict)  # username -> sub
    fixed_ids_kept: dict[str, bool] = field(default_factory=dict)
    drift: list[str] = field(default_factory=list)
    entries_written: list[str] = field(default_factory=list)  # names only, never values
    broker_config_unchanged: bool = False


def persona_entry(username: str) -> str:
    return f"STEWARDRY_PERSONA_PASSWORD_{username.upper()}"


def check_issuer(issuer: str, realm: str) -> str:
    """The admin API base URL, if the issuer is a local hub for this realm."""
    parts = urlsplit(issuer.rstrip("/"))
    if parts.scheme not in ("http", "https") or parts.hostname not in LOCAL_HOSTS:
        raise BootstrapError("the hub issuer must be a local hub (localhost or 127.0.0.1)")
    if parts.path != f"/realms/{realm}":
        raise BootstrapError(f"the hub issuer must be the {realm!r} realm (…/realms/{realm})")
    return f"{parts.scheme}://{parts.netloc}"


# ----------------------------------------------------------------- secrets


def read_secrets(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    entries = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if "=" in line and not line.lstrip().startswith("#"):
            name, value = line.split("=", 1)
            entries[name.strip()] = value.strip()
    return entries


def write_secrets(path: Path, entries: Mapping[str, str]) -> None:
    """Rewrite the file with owner-only permissions. Values are never printed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Generated by `stewardry hub bootstrap`. Git-ignored. Do not share."]
    lines += [f"{name}={value}" for name, value in sorted(entries.items())]
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    os.chmod(path, stat.S_IRUSR | stat.S_IWUSR)


# ----------------------------------------------------------------- admin API


class KeycloakAdmin:
    def __init__(self, base: str, realm: str, http: httpx2.Client) -> None:
        self.base = base
        self.realm = realm
        self.http = http
        self._token: str | None = None

    def _check(self, response: httpx2.Response, what: str) -> httpx2.Response:
        if response.status_code >= 400:
            raise BootstrapError(f"{what} failed (HTTP {response.status_code})")
        return response

    def login(self, username: str, password: str) -> None:
        response = self.http.post(
            f"{self.base}/realms/master/protocol/openid-connect/token",
            data={
                "grant_type": "password",
                "client_id": "admin-cli",
                "username": username,
                "password": password,
            },
        )
        self._check(response, "admin sign-in")
        self._token = str(response.json()["access_token"])

    def discovery_issuer(self) -> str:
        response = self.http.get(
            f"{self.base}/realms/{self.realm}/.well-known/openid-configuration"
        )
        return str(self._check(response, "reading the hub's discovery document").json()["issuer"])

    def _admin(self, method: str, path: str, what: str, **kwargs: Any) -> httpx2.Response:
        if self._token is None:
            raise BootstrapError("not signed in to the admin API")
        response = self.http.request(
            method,
            f"{self.base}/admin/realms/{self.realm}{path}",
            headers={"Authorization": f"Bearer {self._token}"},
            **kwargs,
        )
        return self._check(response, what)

    def clients(self) -> list[dict[str, Any]]:
        result: list[dict[str, Any]] = self._admin("GET", "/clients", "listing clients").json()
        return result

    def client_scopes(self) -> list[dict[str, Any]]:
        result: list[dict[str, Any]] = self._admin(
            "GET", "/client-scopes", "listing client scopes"
        ).json()
        return result

    def create_client(self, representation: Mapping[str, Any]) -> None:
        self._admin("POST", "/clients", "creating the stewardry client", json=representation)

    def find_user(self, username: str) -> dict[str, Any] | None:
        users = self._admin(
            "GET",
            "/users",
            f"looking up user {username}",
            params={"username": username, "exact": "true"},
        ).json()
        return next((u for u in users if u.get("username") == username), None)

    def import_users(self, users: list[dict[str, Any]]) -> None:
        self._admin(
            "POST",
            "/partialImport",
            "importing persona users",
            json={"ifResourceExists": "SKIP", "users": users},
        )


# ----------------------------------------------------------------- bootstrap


def _canonical(items: list[dict[str, Any]], skip: str | None = None) -> str:
    kept = [i for i in items if i.get("clientId") != skip]
    return json.dumps(sorted(kept, key=lambda i: str(i.get("id"))), sort_keys=True)


def bootstrap(
    admin: KeycloakAdmin,
    issuer: str,
    additions: Mapping[str, Any],
    secrets_file: Path,
    include_optional: bool = False,
) -> BootstrapResult:
    result = BootstrapResult()
    if admin.discovery_issuer().rstrip("/") != issuer.rstrip("/"):
        raise BootstrapError("the hub's discovery document names a different issuer; stopped")
    client_spec = dict(additions["client"])
    client_id = client_spec["clientId"]
    before_clients = _canonical(admin.clients(), skip=client_id)
    before_scopes = _canonical(admin.client_scopes())
    stored = read_secrets(secrets_file)
    entries = dict(stored)

    existing = next((c for c in admin.clients() if c.get("clientId") == client_id), None)
    if existing is None:
        secret = secrets.token_urlsafe(32)
        admin.create_client(client_spec | {"secret": secret})
        entries[CLIENT_ENTRY] = secret
        result.entries_written.append(CLIENT_ENTRY)
        result.client = "created"
    else:
        result.client = "existed"
        for name in CHECKED_CLIENT_FIELDS:
            if name in existing and existing[name] != client_spec[name]:
                result.drift.append(f"client {client_id}: {name} differs from the additions file")
        if CLIENT_ENTRY not in entries:
            result.drift.append(
                f"client {client_id} exists but its secret is not in {secrets_file.name}; "
                "it was not regenerated"
            )

    for username in additions["existing_users"]:
        user = admin.find_user(username)
        if user is None:
            raise BootstrapError(f"user {username} from the broker's realm was not found")
        result.subjects[username] = str(user["id"])
        result.existing_users.append(username)

    wanted = list(additions["users"]) + (
        list(additions.get("optional_users", [])) if include_optional else []
    )
    to_import = []
    for spec in wanted:
        if admin.find_user(spec["username"]) is not None:
            result.existing_users.append(spec["username"])
            continue
        password = secrets.token_urlsafe(18)
        entries[persona_entry(spec["username"])] = password
        result.entries_written.append(persona_entry(spec["username"]))
        to_import.append(
            {
                "id": spec["id"],
                "username": spec["username"],
                "enabled": True,
                "firstName": spec["firstName"],
                "lastName": spec["lastName"],
                "email": f"{spec['username']}@stewardry.invalid",
                "emailVerified": True,
                "credentials": [{"type": "password", "value": password, "temporary": False}],
            }
        )
        result.created_users.append(spec["username"])
    if to_import:
        admin.import_users(to_import)
    for spec in wanted:
        user = admin.find_user(spec["username"])
        if user is None:
            raise BootstrapError(f"user {spec['username']} was not created")
        result.subjects[spec["username"]] = str(user["id"])
        result.fixed_ids_kept[spec["username"]] = user["id"] == spec["id"]

    if result.entries_written:
        write_secrets(secrets_file, entries)

    after_clients = _canonical(admin.clients(), skip=client_id)
    after_scopes = _canonical(admin.client_scopes())
    result.broker_config_unchanged = (before_clients, before_scopes) == (
        after_clients,
        after_scopes,
    )
    if not result.broker_config_unchanged:
        raise BootstrapError("the broker's clients or client scopes changed; investigate")
    return result


def proposed_mapping(example: Path, subjects: Mapping[str, str]) -> dict[str, Any]:
    """The example access mapping with each placeholder replaced by the real
    subject. Users the hub does not have are left out."""
    data: dict[str, Any] = yaml.safe_load(example.read_text(encoding="utf-8"))
    users = []
    for user in data["users"]:
        if user["username"] in subjects:
            users.append(user | {"sub": subjects[user["username"]]})
    if "sales2" in subjects:
        users.append(
            {
                "username": "sales2",
                "sub": subjects["sales2"],
                "display_name": "Second Sales persona (synthetic)",
                "roles": ["sales"],
                "customers": ["quillon-synthetic"],
            }
        )
    return data | {"users": users}
